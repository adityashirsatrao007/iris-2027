"""Make the svmult manuscript fit the IRIS ten-page ceiling.

The compact version retains the provenance method, paired detector audit,
same-benchmark control, uncertainty analysis, and threats. Cross-generator
holdout details remain in the reproducibility artifacts and can be supplied as
supplementary material.
"""
from pathlib import Path

p = Path("paper/main_svmult.tex")
s = p.read_text(encoding="utf-8")

start = s.index(r"\section{Related Work}")
end = s.index(r"\section{Method}", start)
replacement = r"""\section{Related Work}

Released detectors such as CNNSpot and UnivFD use low-level image statistics and
cross-generator features to distinguish authentic from generated images
\cite{wang2020cnnspot,ojha2023univfd}. Benchmarks such as GenImage evaluate
generator transfer and generic degradation \cite{zhu2023genimage}. Restoration
models rewrite the same signal through denoising, enhancement, or
super-resolution \cite{wang2021realesrgan,zamir2022restormer}. Recent
transformation-based detectors use these operators to improve binary detection;
our question is different: whether an authentic restored photograph should be
treated as a separate provenance state and whether released detectors falsely
flag it. We therefore use source-paired original/restored images and report
detector-dependent changes rather than claiming universal failure.

"""
s = s[:start] + replacement + s[end:]

start = s.index(r"\subsection{Generalisation to an unseen generator family}")
end = s.index(r"\section{Threats to Validity}", start)
replacement = r"""\subsection{Generalisation beyond the primary generators}

The saved protocol results also include a leave-one-generator-family-out audit.
Its mean AUROC is 0.978, with GLIDE the hardest held-out family (0.932). The
full per-family table and figure are retained in the repository as supplementary
reproducibility material; the main paper focuses on the restoration audit and
its matched-benchmark control.

"""
s = s[:start] + replacement + s[end:]

start = s.index(r"\subsection{Implementation}")
end = s.index(r"\section{Results}", start)
replacement = r"""\subsection{Implementation}

The final restoration and official-detector experiments use CUDA on an NVIDIA
GeForce GTX 1650 Ti. Probe seeds and checkpoint paths are recorded with the
prediction files. Every reported number is regenerated by the repository
harness from saved predictions rather than entered by hand.

"""
s = s[:start] + replacement + s[end:]

# Keep only the two core figures in the compact proceedings version.
for marker in ("fig_probe_roc", "fig_detector_delta", "fig_detector_threshold_delta"):
    if marker in s:
        a = s.index(r"\begin{figure}[t]", s.index(marker) - 200)
        b = s.index(r"\end{figure}", a) + len(r"\end{figure}")
        s = s[:a] + s[b:]

Path("paper/main_svmult.tex").write_text(s, encoding="utf-8")
print("Wrote compact paper/main_svmult.tex")
